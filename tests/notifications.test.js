import { test } from "node:test";
import assert from "node:assert/strict";
import request from "supertest";
import { chromium } from "playwright";
import fs from "node:fs/promises";
import path from "node:path";
import AdmZip from "adm-zip";
process.env.APP_ORIGIN = "http://127.0.0.1:3196";
const { app } = await import("../server/app.js");
const { db, encrypt, decrypt, dataDir } = await import("../server/core.js");
const { createBackup, restoreBackup, archivePath, backupPath } = await import("../server/backup.js");
if (process.env.NODE_ENV !== "test") throw Error("Gunakan database tes terpisah");
test("notifikasi antaradmin, pengingat, isolasi, UI dan backup", async (t) => {
  const server = app.listen(3196, "127.0.0.1"); await new Promise((r) => server.once("listening", r));
  const a = request.agent(server), b = request.agent(server), c = request.agent(server);
  const login = async (agent, email, password) => {
    const token = (await agent.get("/api/csrf")).body.token;
    await agent.post("/api/auth/login").set("X-CSRF-Token", token).send({ email, password }).expect(200);
    await agent.post("/api/admin/mode").set("X-CSRF-Token", token).send({ mode: "internal" }).expect(200);
    return token;
  };
  let browser;
  try {
    const ac = await login(a, process.env.ADMIN_EMAIL, process.env.ADMIN_PASSWORD);
    const post = (agent, token, url, body = {}) => agent.post("/api/admin/" + url).set("X-CSRF-Token", token).send(body);
    for (const name of ["penerima", "lain"]) await post(a, ac, "admins", { name: "Admin " + name, email: name + "@notif.test", password: "TestNotif!2026", role: "admin", active: true }).expect(200);
    const bc = await login(b, "penerima@notif.test", "TestNotif!2026"), cc = await login(c, "lain@notif.test", "TestNotif!2026");
    const receiver = await db.admin.findUnique({ where: { email: "penerima@notif.test" } });
    const payload = { title: "Pengingat dokumen", message: 'Periksa dokumen <img src=x onerror="window.__notifXss=1">', kind: "reminder", recipients: [receiver.id] };
    let first, future;
    await t.test("auth, CSRF dan daftar penerima tanpa rahasia", async () => {
      await request(server).get("/api/admin/notifications").expect(401);
      await a.post("/api/admin/notifications").send(payload).expect(403);
      const recipients = (await b.get("/api/admin/notifications/recipients").expect(200)).body;
      assert.ok(recipients.some((r) => r.id === receiver.id));
      assert.ok(recipients.every((r) => Object.keys(r).every((k) => ["id", "name"].includes(k))));
    });
    await t.test("pesan hanya terlihat oleh penerima; baca idempoten dan tidak memengaruhi admin lain", async () => {
      first = (await post(a, ac, "notifications", payload).expect(201)).body;
      assert.equal((await b.get("/api/admin/notifications/unread")).body.unread, 1);
      assert.equal((await c.get("/api/admin/notifications")).body.total, 0);
      await post(c, cc, `notifications/${first.id}/read`).expect(404);
      await post(b, bc, `notifications/${first.id}/read`).expect(200);
      const before = await db.adminNotificationRecipient.findFirst({ where: { notificationId: first.id } });
      await post(b, bc, `notifications/${first.id}/read`).expect(200);
      assert.equal(+(await db.adminNotificationRecipient.findUnique({ where: { id: before.id } })).readAt, +before.readAt);
      assert.equal((await b.get("/api/admin/notifications/unread")).body.unread, 0);
    });
    await t.test("pengingat masa depan tidak dihitung/dibaca; muncul setelah waktu tiba tanpa scheduler", async () => {
      future = (await post(a, ac, "notifications", { ...payload, dueAt: new Date(Date.now() + 3600000).toISOString() }).expect(201)).body;
      await post(b, bc, `notifications/${future.id}/read`).expect(404);
      await post(b, bc, "notifications/read-all").expect(200);
      assert.equal((await b.get("/api/admin/notifications/unread")).body.unread, 0);
      await db.adminNotification.update({ where: { id: future.id }, data: { dueAt: new Date(Date.now() - 1000) } });
      assert.equal((await b.get("/api/admin/notifications/unread")).body.unread, 1);
    });
    await t.test("isolasi mode, hanya pengirim/Super Admin dapat membatalkan", async () => {
      await post(b, bc, `notifications/${future.id}/cancel`).expect(404);
      await post(b, bc, "mode", { mode: "eksternal" }).expect(200);
      assert.equal((await b.get("/api/admin/notifications/unread")).body.unread, 0);
      await post(b, bc, `notifications/${future.id}/read`).expect(404);
      await post(b, bc, "mode", { mode: "internal" });
      await post(a, ac, `notifications/${future.id}/cancel`).expect(200);
      assert.equal((await b.get("/api/admin/notifications/unread")).body.unread, 0);
    });
    await t.test("admin biasa dapat membuat pesan semua admin dan input tidak valid ditolak", async () => {
      await post(b, bc, "notifications", { ...payload, all: true }).expect(201);
      await post(a, ac, "notifications", { ...payload, recipients: ["tidak-ada"] }).expect(422);
      await post(a, ac, "notifications", { ...payload, recipients: [] }).expect(422);
      await post(a, ac, "notifications", { ...payload, dueAt: "salah" }).expect(422);
      await post(a, ac, "notifications", { ...payload, dueAt: "2020-01-01T00:00:00.000Z" }).expect(422);
    });
    await t.test("browser: badge, form pesan, pembacaan, XSS dan tampilan mobile", async () => {
      browser = await chromium.launch({ headless: true });
      const context = await browser.newContext(), page = await context.newPage(), errors = [];
      page.on("pageerror", (e) => errors.push(e.message));
      const token = (await (await context.request.get("http://127.0.0.1:3196/api/csrf")).json()).token;
      await context.request.post("http://127.0.0.1:3196/api/auth/login", { headers: { "X-CSRF-Token": token }, data: { email: "penerima@notif.test", password: "TestNotif!2026" } });
      await context.request.post("http://127.0.0.1:3196/api/admin/mode", { headers: { "X-CSRF-Token": token }, data: { mode: "internal" } });
      await page.goto("http://127.0.0.1:3196/admin");
      const summary = page.locator(".notification-summary");
      await summary.getByRole("heading", { name: "Notifikasi masuk", exact: true }).waitFor();
      await summary.getByRole("heading", { name: "Pengingat dokumen", exact: true }).first().waitFor();
      assert.equal(await page.getByRole("button", { name: /Tandai .*ditinjau/ }).count(), 0);
      assert.equal(await summary.locator("article").count(), 1);
      await summary.getByText("1 dari 2", { exact: false }).waitFor();
      await summary.getByRole("button", { name: "Notifikasi berikutnya", exact: true }).click();
      await summary.getByText("2 dari 2", { exact: false }).waitFor();
      await summary.getByRole("button", { name: "Notifikasi sebelumnya", exact: true }).click();
      await summary.getByText("1 dari 2", { exact: false }).waitFor();
      assert.equal(await summary.locator("img").count(), 0);
      await page.getByRole("button", { name: "⇄ Pindah mode", exact: true }).click();
      await summary.getByText("Belum ada notifikasi masuk.", { exact: true }).waitFor();
      await page.getByRole("button", { name: "⇄ Pindah mode", exact: true }).click();
      await summary.locator(".notification-unread").waitFor();
      await page.getByRole("button", { name: "Notifikasi, 1 belum dibaca" }).click();
      const popup = page.getByRole("dialog", { name: "Notifikasi terbaru" });
      await popup.waitFor();
      assert.equal(await page.getByRole("heading", { name: "Ringkasan", exact: true }).count(), 1);
      await page.getByRole("heading", { name: "Pengingat dokumen" }).first().waitFor();
      assert.equal(await page.locator(".notification-message img").count(), 0);
      assert.equal(await page.evaluate(() => window.__notifXss), undefined);
      await page.setViewportSize({ width: 390, height: 844 });
      assert.ok((await popup.boundingBox()).width <= 390);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.screenshot({ path: "test-results/notifications-popup-mobile.png", fullPage: true });
      await page.setViewportSize({ width: 1440, height: 1000 });
      await popup.getByRole("button", { name: "Tandai semua dibaca" }).click();
      await page.getByRole("button", { name: "Notifikasi, 0 belum dibaca" }).waitFor();
      await page.keyboard.press("Escape");
      await popup.waitFor({ state: "hidden" });
      assert.equal(await popup.count(), 0);
      await summary.locator(".notification-unread").waitFor({ state: "hidden" });
      assert.equal(await summary.locator(".notification-unread").count(), 0);
      assert.ok(await page.locator(".notification-bell").evaluate((el) => el === document.activeElement));
      await summary.getByRole("button", { name: "Buka kotak masuk →", exact: true }).click();
      await page.getByRole("button", { name: "Buat notifikasi / pengingat" }).click();
      await page.getByLabel("Judul", { exact: true }).fill("Pesan browser");
      await page.getByLabel("Isi pesan").fill("Pesan pengujian diri sendiri");
      await page.getByRole("button", { name: "Simpan notifikasi" }).click();
      await page.getByRole("heading", { name: "Pesan browser" }).waitFor();
      await page.locator(".notification-bell").click();
      const popupMessage = popup.locator("article").filter({ has: page.getByRole("heading", { name: "Pesan browser", exact: true }) });
      await popupMessage.getByRole("button", { name: "Tandai dibaca", exact: true }).click();
      await popupMessage.getByText("Dibaca", { exact: true }).waitFor();
      await page.keyboard.press("Escape"); await popup.waitFor({ state: "hidden" });
      const inboxMessage = page.locator(".notification-list article").filter({ has: page.getByRole("heading", { name: "Pesan browser", exact: true }) });
      await inboxMessage.getByText("Dibaca", { exact: true }).waitFor({ timeout: 2000 });
      await page.getByRole("button", { name: "Buat notifikasi / pengingat" }).click();
      await page.getByLabel("Judul", { exact: true }).fill("Pengingat terjadwal");
      await page.getByLabel("Isi pesan").fill("Pengingat pengujian besok");
      await page.getByLabel("Jenis", { exact: false }).selectOption("reminder");
      await page.getByLabel("Prioritas", { exact: false }).selectOption("urgent");
      await page.getByLabel("Jadwalkan waktu muncul").check();
      const local = await page.evaluate(() => {
        const d = new Date(Date.now() + 86400000), pad = (v) => String(v).padStart(2, "0");
        return `${d.getFullYear()}-${pad(d.getMonth()+1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`;
      });
      await page.getByLabel("Waktu pengingat", { exact: false }).fill(local);
      await page.getByRole("button", { name: "Simpan notifikasi" }).click();
      await page.getByText("Pengingat berhasil dijadwalkan.", { exact: true }).waitFor();
      await page.getByRole("button", { name: "Terkirim / terjadwal", exact: true }).click();
      const scheduled = page.locator("article").filter({ has: page.getByRole("heading", { name: "Pengingat terjadwal" }) });
      await scheduled.getByText("Terjadwal", { exact: true }).waitFor();
      page.once("dialog", (dialog) => dialog.accept());
      await scheduled.getByRole("button", { name: "Batalkan notifikasi" }).click();
      await scheduled.getByText("Dibatalkan", { exact: true }).waitFor();
      await page.setViewportSize({ width: 390, height: 844 });
      await page.locator(".sidebar").evaluate((el) => Promise.all(el.getAnimations().map((animation) => animation.finished.catch(() => {}))));
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.screenshot({ path: "test-results/notifications-mobile.png", fullPage: true });
      assert.deepEqual(errors, []); await browser.close(); browser = null;
    });
    await t.test("backup/restore menyimpan notifikasi dan status baca", async () => {
      const req = { admin: { email: "tes-notifikasi" }, mode: "internal", ip: "test" };
      const count = await db.adminNotification.count(), reads = await db.adminNotificationRecipient.count({ where: { readAt: { not: null } } });
      const backup = await createBackup(req);
      await db.adminNotificationRecipient.deleteMany(); await db.adminNotification.deleteMany();
      await restoreBackup(backup.id, req);
      assert.equal(await db.adminNotification.count(), count);
      assert.equal(await db.adminNotificationRecipient.count({ where: { readAt: { not: null } } }), reads);
      const zip = new AdmZip(decrypt(await fs.readFile(archivePath(backup.filename))));
      const manifest = JSON.parse(zip.readAsText("database.json"));
      delete manifest.tables.adminNotification; delete manifest.tables.adminNotificationRecipient;
      zip.updateFile("database.json", Buffer.from(JSON.stringify(manifest)));
      const filename = path.join(await backupPath(), "legacy-notifications.zip.enc"), bytes = encrypt(zip.toBuffer()); await fs.writeFile(filename, bytes);
      const legacy = await db.backup.create({ data: { filename: path.relative(dataDir, filename).replaceAll("\\", "/"), size: bytes.length, status: "selesai" } });
      await restoreBackup(legacy.id, req); assert.equal(await db.adminNotification.count(), 0);
    });
  } finally { if (browser) await browser.close(); await new Promise((r) => server.close(r)); await db.$disconnect(); }
});
